import { readFileSync, writeFileSync } from "node:fs";
import { isEntry } from "../src/cli/entry.ts";

interface SeedProduct {
  name: string;
  category: string;
  isStaple: boolean;
  roles: string[];
  isFreshProduce: boolean;
  seasonMonths: number[] | null;
  shelfLifeDays: number | null;
  openedShelfLifeDays: number | null;
  defaultUnit: string;
}

const lit = (v: unknown): string => {
  if (v === null) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "1" : "0";
  return `'${String(v).replaceAll("'", "''")}'`;
};

export function seedSql(): string {
  const seed = JSON.parse(readFileSync(new URL("../data/products.seed.json", import.meta.url), "utf8")) as { products: SeedProduct[] };
  const rows = seed.products.map((p, i) =>
    `(${[i + 1, p.name, p.category, p.isStaple, JSON.stringify(p.roles), p.isFreshProduce,
      p.seasonMonths === null ? null : JSON.stringify(p.seasonMonths), p.shelfLifeDays, p.openedShelfLifeDays, p.defaultUnit].map(lit).join(", ")})`,
  );
  return [
    "-- Generated by `npm run seed:sql` from data/products.seed.json. Do not edit by hand.",
    "INSERT INTO products (id, name, category, is_staple, roles, is_fresh_produce, season_months, shelf_life_days, opened_shelf_life_days, default_unit) VALUES",
    `${rows.join(",\n")};`,
    "",
  ].join("\n");
}

if (isEntry(import.meta.url)) {
  writeFileSync(new URL("../migrations/0002_seed_products.sql", import.meta.url), seedSql());
}
